<?php

declare(strict_types=1);

use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Schema;
use IzAhmad\TurboSeeder\Facades\TurboSeeder;

function createSequenceTable(string $kind, string $name = 'sequence_items'): void
{
    Schema::dropIfExists($name);

    if ($kind === 'identity') {
        $prefix = DB::connection()->getTablePrefix();
        DB::statement("CREATE TABLE \"{$prefix}{$name}\" (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, n integer)");

        return;
    }

    Schema::create($name, function ($table) {
        $table->id();
        $table->integer('n');
    });
}

function seedExplicitIds(string $strategy, int $count = 5, int $offset = 1, string $table = 'sequence_items'): mixed
{
    $builder = TurboSeeder::forTable($table)
        ->columns(['id', 'n'])
        ->generate(fn ($i) => ['id' => $i + $offset, 'n' => $i])
        ->count($count)
        ->withoutProgressTracking();

    if ($strategy === 'csv') {
        $builder->useCsvStrategy();
    }

    return $builder->run();
}

afterEach(function () {
    Schema::dropIfExists('sequence_items');
});

foreach (['serial', 'identity'] as $kind) {
    foreach (['default', 'csv'] as $strategy) {
        test("next insert after explicit ids does not collide for {$kind} with the {$strategy} strategy", function () use ($kind, $strategy) {
            createSequenceTable($kind);

            seedExplicitIds($strategy);

            expect(DB::table('sequence_items')->insertGetId(['n' => 99]))->toBe(6);
        })->skip(fn () => DB::getDriverName() !== 'pgsql', 'PostgreSQL-specific');
    }
}

test('a dry run leaves the sequence alone', function () {
    createSequenceTable('serial');

    TurboSeeder::forTable('sequence_items')
        ->columns(['id', 'n'])
        ->generate(fn ($i) => ['id' => $i + 100, 'n' => $i])
        ->count(5)
        ->dryRun()
        ->withoutProgressTracking()
        ->run();

    expect(DB::table('sequence_items')->insertGetId(['n' => 99]))->toBe(1);
})->skip(fn () => DB::getDriverName() !== 'pgsql', 'PostgreSQL-specific');

test('the sequence is never lowered by seeding smaller explicit ids', function () {
    createSequenceTable('serial');
    DB::statement("SELECT setval(pg_get_serial_sequence('sequence_items', 'id'), 1000)");

    seedExplicitIds('default');

    expect(DB::table('sequence_items')->insertGetId(['n' => 99]))->toBe(1001);
})->skip(fn () => DB::getDriverName() !== 'pgsql', 'PostgreSQL-specific');

test('seeding without the id column leaves sequence-generated ids intact', function () {
    createSequenceTable('serial');

    TurboSeeder::forTable('sequence_items')
        ->columns(['n'])
        ->generate(fn ($i) => ['n' => $i])
        ->count(5)
        ->withoutProgressTracking()
        ->run();

    expect(DB::table('sequence_items')->insertGetId(['n' => 99]))->toBe(6);
})->skip(fn () => DB::getDriverName() !== 'pgsql', 'PostgreSQL-specific');

test('a table without any sequence seeds successfully', function () {
    Schema::dropIfExists('sequence_items');
    Schema::create('sequence_items', function ($table) {
        $table->string('code')->primary();
    });

    $result = TurboSeeder::forTable('sequence_items')
        ->columns(['code'])
        ->generate(fn ($i) => ['code' => "c{$i}"])
        ->count(5)
        ->withoutProgressTracking()
        ->run();

    expect($result->success)->toBeTrue()
        ->and(DB::table('sequence_items')->count())->toBe(5);
});

test('the sequence of a prefixed table is advanced', function () {
    DB::connection()->setTablePrefix('pfx_');

    try {
        createSequenceTable('identity');
        seedExplicitIds('default');

        expect(DB::table('sequence_items')->insertGetId(['n' => 99]))->toBe(6);
    } finally {
        Schema::dropIfExists('sequence_items');
        DB::connection()->setTablePrefix('');
    }
})->skip(fn () => DB::getDriverName() !== 'pgsql', 'PostgreSQL-specific');

test('a failed sequence sync only logs a warning and the seed still succeeds', function (string $strategy) {
    createSequenceTable('serial');
    DB::statement('ALTER SEQUENCE sequence_items_id_seq MAXVALUE 3');
    Log::spy();

    $result = seedExplicitIds($strategy);

    expect($result->success)->toBeTrue()
        ->and($result->recordsInserted)->toBe(5)
        ->and(DB::table('sequence_items')->count())->toBe(5);

    Log::shouldHaveReceived('warning')
        ->withArgs(fn ($message) => str_contains($message, 'could not be advanced'))
        ->once();
})->with(['default', 'csv'])->skip(fn () => DB::getDriverName() !== 'pgsql', 'PostgreSQL-specific');

test('a failed sequence sync does not abort a surrounding transaction', function () {
    createSequenceTable('serial');
    DB::statement('ALTER SEQUENCE sequence_items_id_seq MAXVALUE 3');

    $count = DB::transaction(function () {
        seedExplicitIds('default');

        return DB::table('sequence_items')->count();
    });

    expect($count)->toBe(5)
        ->and(DB::table('sequence_items')->count())->toBe(5);
})->skip(fn () => DB::getDriverName() !== 'pgsql', 'PostgreSQL-specific');
